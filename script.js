const slides = [...document.querySelectorAll(".testimonial-slide")];
const videos = [...document.querySelectorAll(".testimonial-video")];


const prevBtn = document.getElementById("testimonial-prev");
const nextBtn = document.getElementById("testimonial-next");


let current = 0;


function pauseAll() {
   videos.forEach(video => {
       video.pause();
   });
}


function updateCarousel() {


   slides.forEach(slide => {
       slide.classList.remove(
           "is-active",
           "is-prev",
           "is-next",
           "is-hidden"
       );
   });


   const prev =
       (current - 1 + slides.length) % slides.length;


   const next =
       (current + 1) % slides.length;


   slides[current].classList.add("is-active");
   slides[prev].classList.add("is-prev");
   slides[next].classList.add("is-next");


   pauseAll();
}


nextBtn.addEventListener("click", () => {


   current++;


   if (current >= slides.length)
       current = 0;


   updateCarousel();


});


prevBtn.addEventListener("click", () => {


   current--;


   if (current < 0)
       current = slides.length - 1;


   updateCarousel();


});




videos.forEach(video=>{


   video.addEventListener("play",()=>{


       videos.forEach(v=>{


           if(v!==video)
               v.pause();


       });


   });


});


updateCarousel();


slides.forEach((slide, index) => {


   slide.addEventListener("click", (e) => {


       // Si on clique sur la vidéo active, on ne fait rien
       if (slide.classList.contains("is-active")) return;


       // Si on clique sur les contrôles de la vidéo, on ne change pas le carousel
       if (e.target.closest("video")) return;


       current = index;
       updateCarousel();


   });


});


videos.forEach((video, index) => {


   video.addEventListener("click", (e) => {


       const slide = slides[index];


       // Si la vidéo n'est pas active, on la ramène au centre
       if (!slide.classList.contains("is-active")) {


           e.preventDefault();
           e.stopPropagation();


           current = index;
           updateCarousel();


           return;
       }


   });


});





